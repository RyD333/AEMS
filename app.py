"""AEMS API - turns a use-case description into Function Point Analysis (FPA) metrics.

POST /analyze  -> runs the fine-tuned model (GGUF, CPU) and post-processes the result
GET  /health   -> liveness check
GET  /docs     -> interactive Swagger UI (auto-generated by FastAPI)
"""
import json
import os
import threading
import time
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field
from llama_cpp import Llama

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.getenv("MODEL_PATH", os.path.join(HERE, "models", "aems-q4.gguf"))
N_CTX = 3072          # same context length the model was trained with
MAX_NEW_TOKENS = 600  # cap on generated tokens per request
# Set N_THREADS to the number of vCPUs given to the container (see Dockerfile).
N_THREADS = int(os.getenv("N_THREADS", os.cpu_count() or 4))

SYSTEM_PROMPT = "Extract FPA metrics."
COMPLEXITY_MULTIPLIER = {"Simple": 5, "Average": 10, "Complex": 15}

llm = None                     # loaded once at startup
llm_lock = threading.Lock()    # llama.cpp handles one request at a time
_decoder = json.JSONDecoder()


@asynccontextmanager
async def lifespan(app: FastAPI):
    global llm
    llm = Llama(model_path=MODEL_PATH, n_ctx=N_CTX, n_threads=N_THREADS, verbose=False)
    yield


app = FastAPI(
    title="AEMS - FPA Estimation API",
    description="Fine-tuned Phi-3.5-mini that extracts Function Point Analysis metrics "
                "from a use case. Output is a draft: review it before use.",
    version="1.0.0",
    lifespan=lifespan,
)


class AnalyzeRequest(BaseModel):
    use_case_name: str = Field(..., min_length=1)
    operation: str = Field(..., min_length=1, description="Add, Edit, View, Search, Delete ...")
    description: str = Field(..., min_length=1)
    actors: str = Field(..., min_length=1)
    basic_flow: str = Field(..., min_length=1)
    alternate_flow: str = Field("", description="Leave empty if there is none")
    fpid: Optional[int] = Field(None, description="Optional ID to echo back in the result")

    model_config = {
        "json_schema_extra": {
            "example": {
                "use_case_name": "4.3 Manage Holiday Calendar",
                "operation": "Add",
                "description": "Allows an HR Administrator to add a new holiday to the yearly holiday calendar.",
                "actors": "HR Administrator",
                "basic_flow": "1. The HR Administrator opens Admin > Holiday Calendar.\n"
                              "2. Clicks 'Add Holiday'.\n"
                              "3. Enters Holiday Name (V100), Holiday Date, Holiday Type, Applicable Office, Status.\n"
                              "4. Clicks 'Save'.\n"
                              "5. The system validates the input, saves the record and shows 'Holiday added successfully'.",
                "alternate_flow": "A1. Mandatory field missing: the system shows an error.\n"
                                  "A2. Holiday already exists on that date: the system shows an error.",
            }
        }
    }


class AnalyzeResponse(BaseModel):
    metrics: dict
    review_notes: list[str]
    inference_seconds: float
    raw_model_output: Optional[str] = None


def build_prompt(r: AnalyzeRequest) -> str:
    """Must match the exact format the model was fine-tuned on."""
    user = (
        f"Target Operation: {r.operation.strip()}\n\n"
        f"Use Case Name: {r.use_case_name.strip()}\n"
        f"Description: {r.description.strip()}\n"
        f"Actors: {r.actors.strip()}\n"
        f"Basic Flow Of Events:\n{r.basic_flow.strip()}\n"
        f"Alternate Flow of Events:\n{r.alternate_flow.strip() or 'None'}"
    )
    return f"<|system|>\n{SYSTEM_PROMPT}<|end|>\n<|user|>\n{user}<|end|>\n<|assistant|>\n"


def extract_first_json(text: str):
    """Return the first complete JSON object in text, or None."""
    try:
        obj, _ = _decoder.raw_decode(text.lstrip())
        return obj if isinstance(obj, dict) else None
    except json.JSONDecodeError:
        return None


def generate_first_json(tokens):
    """Stream tokens and stop as soon as one full JSON object has been produced
    (the model sometimes keeps going and repeats itself - this saves time)."""
    text = ""
    for chunk in llm(tokens, max_tokens=MAX_NEW_TOKENS, temperature=0.0,
                     stream=True, stop=["<|end|>"]):
        text += chunk["choices"][0]["text"]
        if text.rstrip().endswith("}"):
            obj = extract_first_json(text)
            if obj is not None:
                return obj, text
    return extract_first_json(text), text


def postprocess(pred: dict, fpid: Optional[int]) -> dict:
    """Fill in values the model should not predict itself:
    DET counts = length of the field lists, Multiplier/Result from Complexity."""
    out = dict(pred)
    if fpid is not None:
        out["FPID"] = fpid
    multiplier = COMPLEXITY_MULTIPLIER.get(pred.get("Complexity"))
    if multiplier is not None:
        out["Multiplier"] = multiplier
        out["Result"] = multiplier
    for prefix in ("Ilf", "Ei", "Eq"):
        out[f"{prefix}Det"] = len(pred.get(f"{prefix}DataElements") or [])
    return out


def build_notes(m: dict) -> list[str]:
    notes = ["Draft output from a small fine-tuned model - review the field lists before use."]
    if m.get("Complexity") not in COMPLEXITY_MULTIPLIER:
        notes.append(f"Unexpected Complexity value: {m.get('Complexity')!r}; Multiplier/Result not set.")
    for prefix in ("Ilf", "Ei", "Eq"):
        if (m.get(f"{prefix}Ret") or 0) > 0 and not m.get(f"{prefix}DataElements"):
            notes.append(f"{prefix}Ret > 0 but the {prefix} field list is empty - likely a model miss.")
    if (m.get("EqRet") or 0) > 0:
        notes.append("EQ field list is the least reliable part of the output - verify it.")
    return notes


@app.get("/")
def root():
    return {"service": "AEMS FPA Estimation API", "docs": "/docs", "health": "/health"}


@app.get("/health")
def health():
    return {"status": "ok", "model_loaded": llm is not None}


@app.post("/analyze", response_model=AnalyzeResponse)
def analyze(req: AnalyzeRequest, debug: bool = False):
    if llm is None:
        raise HTTPException(status_code=503, detail="Model is still loading, try again shortly.")

    prompt = build_prompt(req)
    tokens = llm.tokenize(prompt.encode("utf-8"), add_bos=True, special=True)
    if len(tokens) + MAX_NEW_TOKENS > N_CTX:
        raise HTTPException(
            status_code=413,
            detail=f"Input too long: {len(tokens)} tokens (limit is about {N_CTX - MAX_NEW_TOKENS}). "
                   "Shorten the description or flows.",
        )

    start = time.perf_counter()
    with llm_lock:
        pred, raw = generate_first_json(tokens)
    elapsed = round(time.perf_counter() - start, 2)

    if pred is None:
        raise HTTPException(
            status_code=502,
            detail={"error": "Model output could not be parsed as JSON.", "raw_model_output": raw[:500]},
        )

    metrics = postprocess(pred, req.fpid)
    return AnalyzeResponse(
        metrics=metrics,
        review_notes=build_notes(metrics),
        inference_seconds=elapsed,
        raw_model_output=raw if debug else None,
    )
